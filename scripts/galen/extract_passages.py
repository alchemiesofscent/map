"""Stage 3: extract route-relevant passages from candidate sentences.

Reads `data/generated/galen/route_candidates.json` (Stage 2 output) and
emits `data/generated/galen/passages.json` conforming to
`schemas/galen/galen-passage.schema.json`.

For each candidate sentence:
- assign a stable `passage_id` (work.book.chapter.ordinal-within-chapter)
- map each place_mention to a curator `place_key` (always — we require all
  routes places to be in `data/galen/lexicon/places.json` so the auto-detector
  emits curator slugs rather than raw Pleiades IDs)
- tag each place_mention with `evidence_category` A/B/C per the consolidated
  routes defined here (which mirror `docs/galen_route_decisions.md`)
- merge human-edited `translation_en` and `materia_mentions[]` from
  `data/galen/translations/passages.json` (a hand-authored file, not
  regenerated by this script)
- attach `route_keys[]` (the consolidated routes the candidate belongs to)
- set `is_route_anchor` per the decisions doc

Translations file format (JSON):
{
    "<passage_id>": {
        "greek": "..."  # auto-mirrored from TEI; do not edit by hand
        "translation_en": "...",
        "materia_mentions": [{"surface": "...", "materia_key": "..."}],
        "is_route_anchor": true|false,
        "notes": "free text"
    },
    ...
}

This script also writes back to `data/galen/translations/passages.json`
on every run — refreshing only the `greek` field per passage so the
curator can read Greek + English side-by-side. translation_en,
materia_mentions, is_route_anchor, and notes are preserved exactly.

Idempotent. Stable passage_ids across re-runs as long as candidate ordering
within a chapter is stable.
"""
