# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def slugify_pleiades_title(title: str) -> str:
    """Fallback place_key for Pleiades-resolved mentions not in the curator
    lexicon. lowercase + strip non-alpha. Used only to fail safely; in practice
    every route-relevant mention should be curator-resolved."""
    s = unicodedata.normalize("NFD", title)
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    s = re.sub(r"[^a-zA-Z0-9]+", "_", s).strip("_").lower()
    return s or "unknown"


def kuhn_to_volume(work: str, book: str) -> str:
    if work == "SMT":
        return "XI" if int(book) <= 5 else "XII"
    if work == "De_antidotis":
        return "XIV"
    return "?"


KUHN_PAGE_RE = re.compile(r"K\.\s*([IVX]+)\s+(\d+)\.(\d+)(?:[–-](?:(\d+)\.)?(\d+))?")


def parse_kuhn(citation: str) -> tuple[str, int, int, int, int] | None:
    m = KUHN_PAGE_RE.match(citation.strip())
    if not m:
        return None
    vol = m.group(1)
    page_s = int(m.group(2))
    line_s = int(m.group(3))
    page_e = int(m.group(4)) if m.group(4) else page_s
    line_e = int(m.group(5)) if m.group(5) else line_s
    return vol, page_s, line_s, page_e, line_e


def passage_id_for(work: str, chapter_ref: str, ordinal: int) -> str:
    """Stable id: smt.9.1.a / de_antidotis.1.2.a etc."""
    work_slug = "smt" if work == "SMT" else "de_antidotis"
    suffix = chr(ord("a") + ordinal)
    return f"{work_slug}.{chapter_ref}.{suffix}"


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------

def load_lexicon() -> dict[str, dict]:
    """Return place_key -> entry."""
    data = json.loads(LEXICON.read_text())
    return {e["place_key"]: e for e in data}


def load_gazetteer_titles() -> dict[str, str]:
    """Return pleiades_id -> title (for fallback slugify only)."""
    g = json.loads(GAZETTEER.read_text())
    return {pid: p["title"] for pid, p in g["places"].items()}


def load_translations() -> dict[str, dict]:
    if not TRANSLATIONS.exists():
        return {}
    raw = json.loads(TRANSLATIONS.read_text())
    return raw.get("passages", raw) if isinstance(raw, dict) else {}


def sync_greek_into_translations(passages: list[dict]) -> None:
    """Mirror each passage's TEI-derived Greek into the curator translations
    file so Greek + English sit side-by-side for review. translation_en,
    materia_mentions, is_route_anchor, and notes are preserved exactly;
    only the `greek` field is rewritten."""
    if not TRANSLATIONS.exists():
        return
    raw = json.loads(TRANSLATIONS.read_text())
    src = raw.get("passages", {}) if isinstance(raw, dict) else {}
    by_id = {p["passage_id"]: p for p in passages}

    rebuilt: dict[str, dict] = {}
    # Preserve existing order; refresh `greek` for known passages.
    for pid, existing in src.items():
        if pid in by_id:
            entry: dict = {"greek": by_id[pid]["greek"]}
            for k in ("translation_en", "materia_mentions", "is_route_anchor", "notes"):
                if k in existing:
                    entry[k] = existing[k]
            rebuilt[pid] = entry
        else:
            rebuilt[pid] = existing  # leave stale entries alone
    # Append any newly-discovered passages with empty curator fields.
    for pid, p in by_id.items():
        if pid in rebuilt:
            continue
        rebuilt[pid] = {
            "greek": p["greek"],
            "translation_en": "",
            "materia_mentions": [],
            "notes": "",
        }

    raw["_authoring_notes"] = (
        "Greek surface forms preserved exactly; English follows scholarly "
        "conventions (Cyprus, Lemnos, Alexandria Troas, Coele Syria, etc.). "
        "Materia mentions cover only substances Galen describes in this "
        "specific passage; broader pharmacological context is captured at "
        "Stage 5 in materia.json. The `greek` field is auto-mirrored from "
        "the TEI by extract_passages.py — edits to it will be overwritten "
        "on the next run."
    )
    raw["passages"] = rebuilt
    TRANSLATIONS.write_text(json.dumps(raw, ensure_ascii=False, indent=2) + "\n")


# ---------------------------------------------------------------------------
# Build
# ---------------------------------------------------------------------------

def evidence_category(place_key: str, route_keys: list[str]) -> str:
    """Compute A/B/C for a mention given the routes it participates in.

    A = place_key in `core_stops` of any of its route_keys
    B = place_key in `context` of any of its route_keys
    C = place_key in `do_not_map` of any route, OR not in any route lists
        (default for stray Pleiades resolutions).

    Materia layer: any place mentioned in a materia-only candidate is
    category B (it's the site of an observation but not a route stop).
    """
    in_route = False
    for rk in route_keys:
        if rk == MATERIA_LAYER_KEY:
            in_route = True
            continue
        r = ROUTES.get(rk)
        if not r:
            continue
        if place_key in r["core_stops"]:
            return "A"
        if place_key in r["context"]:
            return "B"
        if place_key in r["do_not_map"]:
            return "C"
        in_route = True
    return "B" if in_route else "C"


def build_passage(
    work: str,
    candidate: dict,
    ordinal_in_chapter: int,
    titles: dict[str, str],
    translation_data: dict,
) -> dict:
    chapter_ref = candidate["chapter_ref"]
    pid = passage_id_for(work, chapter_ref, ordinal_in_chapter)
    book = candidate["book"]

    # Kühn span across the candidate's sentences
    parsed = [parse_kuhn(s["kuhn_citation"]) for s in candidate["sentences"]]
    parsed = [p for p in parsed if p]
    if parsed:
        vol = parsed[0][0]
        page_start = min(p[1] for p in parsed)
        line_start = min(p[2] for p in parsed if p[1] == page_start)
        page_end = max(p[3] for p in parsed)
        line_end = max(p[4] for p in parsed if p[3] == page_end)
    else:
        vol = kuhn_to_volume(work, book)
        page_start = page_end = 0
        line_start = line_end = 0

    # Concatenated greek
    greek = " ".join(s["greek"] for s in candidate["sentences"])

    # Routes for this candidate
    route_keys = CANDIDATE_ROUTES.get((work, chapter_ref, ordinal_in_chapter), [])
    routes_for_categorization = [k for k in route_keys if k != MATERIA_LAYER_KEY]

    # Place mentions: collapse per-sentence mentions into per-passage list.
    # Prefer the explicit `place_keys` (curator-resolved slug) when the survey
    # produced it; otherwise fall back to slugifying the Pleiades title.
    seen: set[tuple[str, str]] = set()
    place_mentions: list[dict] = []
    for sent in candidate["sentences"]:
        for m in sent["place_mentions"]:
            place_keys = m.get("place_keys") or []
            ids = m.get("pleiades_ids", []) or []
            if place_keys:
                place_key = place_keys[0]
            elif ids:
                primary = ids[0]
                if primary.isdigit():
                    title = titles.get(primary, primary)
                    place_key = slugify_pleiades_title(title)
                else:
                    # Backward-compat path: an older route_candidates.json
                    # might still encode curator slugs as pleiades_ids.
                    place_key = primary
            else:
                continue
            key = (m["surface"], place_key)
            if key in seen:
                continue
            seen.add(key)
            cat = evidence_category(place_key, routes_for_categorization)
            place_mentions.append({
                "surface": m["surface"],
                "place_key": place_key,
                "evidence_category": cat,
            })

    # Materia mentions + translation come from the hand-authored translations file
    overrides = translation_data.get(pid, {})
    translation_en = overrides.get("translation_en", "")
    materia_mentions = overrides.get("materia_mentions", [])
    is_anchor_override = overrides.get("is_route_anchor")

    # is_route_anchor: explicit override wins; else use PRIMARY_ANCHORS
    if is_anchor_override is not None:
        is_anchor = bool(is_anchor_override)
    else:
        is_anchor = (work, chapter_ref, ordinal_in_chapter) in PRIMARY_ANCHORS

    return {
        "passage_id": pid,
        "work": work,
        "kuhn_volume": vol,
        "kuhn_page_start": page_start,
        "kuhn_line_start": line_start,
        "kuhn_page_end": page_end,
        "kuhn_line_end": line_end,
        "tei_div_path": f"urn:cts:greekLit:tlg0057.{'tlg075' if work == 'SMT' else 'tlg078'}.1st1K-grc1:{chapter_ref}",
        "greek": greek,
        "translation_en": translation_en,
        "route_keys": [k for k in route_keys if k != MATERIA_LAYER_KEY],
        "place_mentions": place_mentions,
        "materia_mentions": materia_mentions,
        "is_route_anchor": is_anchor,
    }


def main() -> int:
    candidates_doc = json.loads(CANDIDATES.read_text())
    lexicon = load_lexicon()
    titles = load_gazetteer_titles()
    translation_data = load_translations()

    passages: list[dict] = []

    for work, candidates in candidates_doc["candidates"].items():
        ordinal_by_chapter: dict[str, int] = {}
        for c in candidates:
            chap = c["chapter_ref"]
            ord_ = ordinal_by_chapter.get(chap, 0)
            ordinal_by_chapter[chap] = ord_ + 1
            passage = build_passage(work, c, ord_, titles, translation_data)
            passages.append(passage)

    OUT_PASSAGES.parent.mkdir(parents=True, exist_ok=True)
    OUT_PASSAGES.write_text(json.dumps(passages, ensure_ascii=False, indent=2))

    sync_greek_into_translations(passages)

    # Console summary
    print(f"Wrote {len(passages)} passages to {OUT_PASSAGES.relative_to(ROOT)}")
    by_route: dict[str, int] = {}
    anchors = 0
    untranslated = 0
    excluded = 0
    place_keys_seen: set[str] = set()
    missing_in_lexicon: set[str] = set()
    for p in passages:
        if p["is_route_anchor"]:
            anchors += 1
        if not p["translation_en"]:
            untranslated += 1
        if not p["route_keys"]:
            excluded += 1
        for rk in p["route_keys"]:
            by_route[rk] = by_route.get(rk, 0) + 1
        for m in p["place_mentions"]:
            place_keys_seen.add(m["place_key"])
            if m["place_key"] not in lexicon:
                missing_in_lexicon.add(m["place_key"])

    print(f"  primary anchors: {anchors}")
    print(f"  untranslated:    {untranslated}")
    print(f"  excluded (no route_keys): {excluded}")
    print(f"  per-route passage counts:")
    for rk, n in sorted(by_route.items()):
        print(f"    {rk}: {n}")
    print(f"  unique place_keys referenced: {len(place_keys_seen)}")
    if missing_in_lexicon:
        print(f"  place_keys NOT in lexicon (synthesized fallback):")
        for pk in sorted(missing_in_lexicon):
            print(f"    {pk}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
